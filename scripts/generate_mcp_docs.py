"""Generate docs/mcp_tools.md from the live MCP server definition.

    uv run python scripts/generate_mcp_docs.py           # write the file
    uv run python scripts/generate_mcp_docs.py --check   # exit 1 if stale

tests/test_mcp_docs.py runs the check, so CI fails when a tool changes
without regenerating the reference.
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import sys
from pathlib import Path
from typing import Any

from fastmcp import Client

from resume_platform.interfaces.mcp.server import mcp
from resume_platform.interfaces.mcp.tools import TOOLS
from resume_platform.paths import PROJECT_ROOT

OUTPUT = PROJECT_ROOT / "docs" / "mcp_tools.md"

SECTIONS = {
    "Versions": [
        "list_resume_versions",
        "create_resume_version",
        "copy_resume_version",
        "delete_resume_version",
    ],
    "Reading": ["load_complete_resume", "list_resume_sections", "read_resume_text"],
    "Editing": [
        "replace_resume_text",
        "insert_resume_text",
        "delete_resume_text",
        "update_resume_section",
    ],
    "Layout": ["get_resume_layout", "set_section_visibility", "set_section_order"],
    "Semantic search": [
        "build_vector_index",
        "search_resume_entries",
        "get_vector_index_status",
    ],
    "Rendering": ["render_resume_pdf", "render_resume_to_overleaf"],
    "Help & diagnostics": [
        "get_resume_yaml_format",
        "diagnose_filesystems",
        "call_me_at_the_first_time_when_you_are_chatgpt",
    ],
}


def _type_of(prop: dict[str, Any]) -> str:
    if "enum" in prop:
        return " \\| ".join(f"`{value}`" for value in prop["enum"])
    if "anyOf" in prop:
        return " \\| ".join(_type_of(option) for option in prop["anyOf"])
    if prop.get("type") == "array":
        return f"{_type_of(prop.get('items', {}))}[]"
    return prop.get("type", "any")


def _hints(annotations: Any) -> str:
    flags = []
    if annotations.readOnlyHint:
        flags.append("read-only")
    else:
        flags.append("writes")
    if annotations.destructiveHint:
        flags.append("destructive")
    if annotations.openWorldHint:
        flags.append("external services")
    return ", ".join(flags)


def _tool_markdown(tool: Any) -> list[str]:
    spec = next(spec for spec in TOOLS if spec.fn.__name__ == tool.name)
    lines = [f"### `{tool.name}`", "", f"_{_hints(tool.annotations)}_", ""]
    lines += [inspect.cleandoc(spec.fn.__doc__ or ""), ""]
    props = tool.inputSchema.get("properties", {})
    required = set(tool.inputSchema.get("required", []))
    if props:
        lines += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
        for name, prop in props.items():
            default = "" if name in required else f" (default `{prop.get('default')}`)"
            description = prop.get("description", "").replace("|", "\\|")
            lines.append(
                f"| `{name}` | {_type_of(prop)} | "
                f"{'yes' if name in required else 'no'} | {description}{default} |"
            )
        lines.append("")
    return lines


async def _list_tools() -> dict[str, Any]:
    async with Client(mcp) as client:
        return {tool.name: tool for tool in await client.list_tools()}


def render() -> str:
    tools = asyncio.run(_list_tools())
    listed = {name for names in SECTIONS.values() for name in names}
    missing = set(tools) - listed
    if missing:
        raise SystemExit(f"Add these tools to SECTIONS: {sorted(missing)}")

    lines = [
        "# MCP tool reference",
        "",
        "<!-- Generated by scripts/generate_mcp_docs.py; do not edit by hand. -->",
        "",
        "Conventions: a resume is addressed by `version_name` (file stem, no",
        "`.yaml`). Text tools take an optional `section_id`; omit it to work on",
        "the whole-resume text view. Failures are returned as MCP tool errors",
        "with an actionable message.",
        "",
    ]
    for title, names in SECTIONS.items():
        lines += [f"## {title}", ""]
        for name in names:
            lines += _tool_markdown(tools[name])
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args(argv)

    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(
                f"{OUTPUT} is out of date; run {Path(__file__).name}", file=sys.stderr
            )
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
